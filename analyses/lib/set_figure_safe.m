function set_figure_safe(F, position, ~)
%SET_FIGURE_SAFE Headless-safe figure setup (normalized position).
% Third argument accepted for drop-in compatibility with setFigure(F, pos, dual).
set(F, ...
    'color', 'w', ...
    'units', 'normalized', ...
    'position', position, ...
    'papersize', [10 6.75], ...
    'paperpositionmode', 'auto');
end
